<?php

namespace App\Modules\Reports\Services;

use App\Modules\Core\Services\SettingService;
use Dompdf\Dompdf;
use Dompdf\Options;
use OpenSpout\Common\Entity\Row;
use OpenSpout\Writer\XLSX\Writer;
use RuntimeException;

/** Converts the canonical spreadsheet-safe report CSV into native documents. */
class ReportDocument
{
    public function __construct(private readonly SettingService $settings) {}

    public function xlsx(string $csv): string
    {
        $path = tempnam(sys_get_temp_dir(), 'report-xlsx-');
        if ($path === false) {
            throw new RuntimeException('Unable to create the report export file.');
        }

        try {
            $writer = new Writer;
            $writer->openToFile($path);
            foreach ($this->rows($csv) as $row) {
                $writer->addRow(Row::fromValues($row));
            }
            $writer->close();

            $content = file_get_contents($path);
            if ($content === false) {
                throw new RuntimeException('Unable to read the report export file.');
            }

            return $content;
        } finally {
            @unlink($path);
        }
    }

    public function pdf(string $csv, string $title, string $language = 'bilingual'): string
    {
        $rtl = in_array($language, ['ar', 'bilingual'], true);
        $lang = $language === 'en' ? 'en' : 'ar';
        $dir = $rtl ? 'rtl' : 'ltr';
        $rows = $this->rows($csv);

        $companyName = $language === 'ar'
            ? $this->settings->get('general', 'company_name_ar', 'نظام إدارة السياحة')
            : $this->settings->get('general', 'company_name_en', 'Tourism ERP');

        $html = '<!doctype html><html lang="'.$lang.'" dir="'.$dir.'"><head><meta charset="UTF-8">'
            .'<style>'
            .'@page{margin:28px 20px 28px 20px;size:A4 landscape;}'
            .'body{font-family:"DejaVu Sans",sans-serif;font-size:8.5px;color:#172033}'
            .'.header{border-bottom:2px solid #172033;padding-bottom:8px;margin-bottom:16px;display:flex;justify-content:space-between;align-items:center}'
            .'.header-company{font-size:14px;font-weight:bold;color:#172033}'
            .'.header-title{font-size:13px;font-weight:bold;color:#4a5568}'
            .'.header-meta{font-size:7.5px;color:#718096;text-align:right}'
            .'table{border-collapse:collapse;width:100%;direction:'.$dir.';margin-top:8px}'
            .'th,td{border:1px solid #d8dee9;padding:4px 5px;text-align:start;vertical-align:top;font-size:8px}'
            .'th{background:#eef2f7;font-weight:bold;color:#172033}'
            .'tr:nth-child(even) td{background:#fafbfc}'
            .'.footer{margin-top:16px;border-top:1px solid #d8dee9;padding-top:8px;font-size:7px;color:#718096}'
            .'.footer .sign-off{margin-top:4px;font-style:italic}'
            .'.page-break{page-break-before:always}'
            .'</style></head><body>'

            // Header
            .'<div class="header">'
            .'<div class="header-company">'.$this->escape($companyName).'</div>'
            .'<div>'
            .'<div class="header-title">'.$this->escape($title).'</div>'
            .'<div class="header-meta">'.date('Y-m-d H:i').'</div>'
            .'</div>'
            .'</div>'

            // Table
            .'<table>';

        foreach ($rows as $index => $row) {
            $tag = $index === 0 ? 'th' : 'td';
            $html .= '<tr>';
            foreach ($row as $cell) {
                $html .= '<'.$tag.'>'.$this->escape($cell).'</'.$tag.'>';
            }
            $html .= '</tr>';
        }
        $html .= '</table>'

            // Footer
            .'<div class="footer">'
            .'<div>Generated by Tourism ERP — '.$this->escape($companyName).'</div>'
            .'<div class="sign-off">Prepared by: ____________________   Approved by: ____________________   Date: ______________</div>'
            .'</div>'

            .'</body></html>';

        $options = new Options;
        $options->set('isRemoteEnabled', false);
        $options->set('isPhpEnabled', false);
        $options->set('defaultFont', 'DejaVu Sans');
        $dompdf = new Dompdf($options);
        $dompdf->setPaper('A4', 'landscape');
        $dompdf->loadHtml($html, 'UTF-8');
        $dompdf->render();

        return $dompdf->output();
    }

    /** @return array<int, array<int, string>> */
    private function rows(string $csv): array
    {
        $csv = preg_replace('/^\xEF\xBB\xBF/', '', $csv) ?? $csv;
        $handle = fopen('php://temp', 'r+');
        fwrite($handle, $csv);
        rewind($handle);

        $rows = [];
        while (($row = fgetcsv($handle)) !== false) {
            $rows[] = array_map(static fn ($cell): string => (string) ($cell ?? ''), $row);
        }
        fclose($handle);

        return $rows;
    }

    private function escape(string $value): string
    {
        return htmlspecialchars($value, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
    }
}
